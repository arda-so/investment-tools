#!/usr/bin/env bash
set -euo pipefail

ROOT="${INVESTOR_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
cd "$ROOT"

need_cmd() {
  command -v "$1" >/dev/null 2>&1 || { echo "missing command: $1" >&2; exit 1; }
}

need_cmd gcloud
need_cmd curl

PROJECT_ID="${PROJECT_ID:-$(gcloud config get-value project 2>/dev/null || true)}"
REGION="${REGION:-europe-west1}"
REPO="${REPO:-investor-tools}"
APP_SERVICE="${APP_SERVICE:-investor-tools-app}"
WORKER_SERVICE="${WORKER_SERVICE:-investor-tools-worker}"
DB_INSTANCE="${DB_INSTANCE:-investor-os-pg}"
# Worker runtime is managed by Cloud Run Jobs; service deploy is optional and off by default.
DEPLOY_WORKER="${DEPLOY_WORKER:-0}"
ALLOW_PUBLIC="${ALLOW_PUBLIC:-0}"
SERVICE_ACCOUNT="${SERVICE_ACCOUNT:-}"

if [ -z "$PROJECT_ID" ] || [ "$PROJECT_ID" = "(unset)" ]; then
  echo "PROJECT_ID is required. Set PROJECT_ID or run: gcloud config set project <id>" >&2
  exit 1
fi

if ! gcloud artifacts repositories describe "$REPO" --location="$REGION" --project="$PROJECT_ID" >/dev/null 2>&1; then
  echo "Artifact Registry repo not found: ${REPO} in ${REGION}" >&2
  exit 1
fi
gcloud secrets describe POSTGRES_DSN --project="$PROJECT_ID" >/dev/null

secret_exists() {
  gcloud secrets describe "$1" --project="$PROJECT_ID" >/dev/null 2>&1
}

SA_OPT=""
if [ -n "$SERVICE_ACCOUNT" ]; then
  SA_OPT="--service-account=$SERVICE_ACCOUNT"
fi

if [ -n "${IMAGE_TAG:-}" ]; then
  TAG="$IMAGE_TAG"
else
  if command -v git >/dev/null 2>&1; then
    TAG="$(git rev-parse --short HEAD 2>/dev/null || true)"
  fi
  TAG="${TAG:-latest}"
fi
IMAGE="${REGION}-docker.pkg.dev/${PROJECT_ID}/${REPO}/app:${TAG}"

if [ "${SKIP_BUILD:-0}" = "1" ]; then
  echo "Using existing image: $IMAGE"
elif [ "${USE_CLOUD_BUILD:-0}" = "1" ] || ! command -v docker >/dev/null 2>&1 || ! docker info >/dev/null 2>&1; then
  echo "Building image: $IMAGE"
  echo "Using Cloud Build (no local Docker required)..."
  gcloud builds submit \
    --project="$PROJECT_ID" \
    --tag="$IMAGE" \
    --machine-type=e2-highcpu-8 \
    .
else
  echo "Building image: $IMAGE"
  docker build -t "$IMAGE" .
  docker push "$IMAGE"
fi

SECRETS="POSTGRES_DSN=POSTGRES_DSN:latest"

AUTH_FLAG="--no-allow-unauthenticated"
if [ "$ALLOW_PUBLIC" = "1" ]; then
  AUTH_FLAG="--allow-unauthenticated"
fi

COMMON_ENV="APP_ENV=cloud,APP_PORT=8080,APP_HOST=0.0.0.0,CORE_DB_BACKEND=postgres,CORE_DB_GUARD_ENFORCE=1,CORE_DB_STRICT_POSTGRES=1,PHASE2_POSTGRES_ENABLED=1,AI_QUEUE_BACKEND=postgres,AI_QUEUE_STRICT_PROD=1,MARKET_SNAPSHOT_REFRESH_ENABLED=0,SEC_POLL_ENABLED=0,FORM4_POLL_ENABLED=0,AUTONOMIC_ENABLED=0,MORNING_BRIEF_ENABLED=0,AI_TIMEOUT_SECONDS=${AI_TIMEOUT_SECONDS:-45},AI_MAX_TOKENS=${AI_MAX_TOKENS:-1200},AI_ENABLE_RESPONSE_CACHE=${AI_ENABLE_RESPONSE_CACHE:-1},AI_CACHE_TTL_SEC=${AI_CACHE_TTL_SEC:-300},AI_CACHE_MAX_ENTRIES=${AI_CACHE_MAX_ENTRIES:-256},AI_CHAT_READONLY=${AI_CHAT_READONLY:-1},AI_COMMAND_SYNC_BUDGET_MS=${AI_COMMAND_SYNC_BUDGET_MS:-38000},ENABLE_IR_AUDIO_TRANSCRIBE=${ENABLE_IR_AUDIO_TRANSCRIBE:-1},AI_PROVIDER=gemini,AI_FALLBACK_PROVIDER=gemini,AI_DISABLE_KEY_PROVIDERS=1,GEMINI_USE_VERTEX_AI=1,GEMINI_USE_NATIVE_SDK=1,GOOGLE_CLOUD_PROJECT=${PROJECT_ID},GOOGLE_CLOUD_LOCATION=${REGION},AI_CASCADE_RECURSIVE_MAX_DEPTH=${AI_CASCADE_RECURSIVE_MAX_DEPTH:-3},ONTOLOGY_TEMPORAL_ENABLED=${ONTOLOGY_TEMPORAL_ENABLED:-1},ONTOLOGY_DECAY_ENABLED=${ONTOLOGY_DECAY_ENABLED:-1},ONTOLOGY_DECAY_HALF_LIFE_DAYS=${ONTOLOGY_DECAY_HALF_LIFE_DAYS:-365},ONTOLOGY_CANONICAL_LLM_ENABLED=${ONTOLOGY_CANONICAL_LLM_ENABLED:-0},ONTOLOGY_CANONICAL_DETERMINISTIC_THRESHOLD=${ONTOLOGY_CANONICAL_DETERMINISTIC_THRESHOLD:-0.97},ONTOLOGY_CANONICAL_LLM_MIN_CONFIDENCE=${ONTOLOGY_CANONICAL_LLM_MIN_CONFIDENCE:-0.86},ONTOLOGY_SIGNED_PROPAGATION_ENABLED=${ONTOLOGY_SIGNED_PROPAGATION_ENABLED:-1},ONTOLOGY_CRITICALITY_REVIEW_ENABLED=${ONTOLOGY_CRITICALITY_REVIEW_ENABLED:-1},ONTOLOGY_CRITICALITY_LLM_ENABLED=${ONTOLOGY_CRITICALITY_LLM_ENABLED:-1},ONTOLOGY_CRITICALITY_LOW_CONF_MAX=${ONTOLOGY_CRITICALITY_LOW_CONF_MAX:-0.72},ONTOLOGY_CRITICALITY_MIN_IMPACT_SCORE=${ONTOLOGY_CRITICALITY_MIN_IMPACT_SCORE:-0.35},ONTOLOGY_CRITICALITY_LLM_MIN_CONFIDENCE=${ONTOLOGY_CRITICALITY_LLM_MIN_CONFIDENCE:-0.65}"
if [ -n "${CLOUD_FILES_BUCKET:-}" ]; then
  COMMON_ENV="${COMMON_ENV},CLOUD_FILES_BUCKET=${CLOUD_FILES_BUCKET}"
fi
if [ -n "${CLOUD_FILES_PREFIX:-}" ]; then
  COMMON_ENV="${COMMON_ENV},CLOUD_FILES_PREFIX=${CLOUD_FILES_PREFIX}"
fi

echo "Deploying app service: ${APP_SERVICE}"
gcloud run deploy "$APP_SERVICE" \
  --image="$IMAGE" \
  --region="$REGION" \
  --project="$PROJECT_ID" \
  --platform=managed \
  "$AUTH_FLAG" \
  $SA_OPT \
  --add-cloudsql-instances="${PROJECT_ID}:${REGION}:${DB_INSTANCE}" \
  --set-env-vars="$COMMON_ENV" \
  --set-secrets="$SECRETS"

if [ "$DEPLOY_WORKER" = "1" ]; then
  echo "Deploying worker service: ${WORKER_SERVICE}"
  WORKER_ENV="APP_ENV=cloud,CORE_DB_BACKEND=postgres,CORE_DB_GUARD_ENFORCE=1,CORE_DB_STRICT_POSTGRES=1,PHASE2_POSTGRES_ENABLED=1,AI_QUEUE_BACKEND=postgres,AI_QUEUE_STRICT_PROD=1,AI_PROVIDER=gemini,AI_FALLBACK_PROVIDER=gemini,AI_DISABLE_KEY_PROVIDERS=1,GEMINI_USE_VERTEX_AI=1,GEMINI_USE_NATIVE_SDK=1,GOOGLE_CLOUD_PROJECT=${PROJECT_ID},GOOGLE_CLOUD_LOCATION=${REGION},AI_CASCADE_RECURSIVE_MAX_DEPTH=${AI_CASCADE_RECURSIVE_MAX_DEPTH:-3},ONTOLOGY_TEMPORAL_ENABLED=${ONTOLOGY_TEMPORAL_ENABLED:-1},ONTOLOGY_DECAY_ENABLED=${ONTOLOGY_DECAY_ENABLED:-1},ONTOLOGY_DECAY_HALF_LIFE_DAYS=${ONTOLOGY_DECAY_HALF_LIFE_DAYS:-365},ONTOLOGY_CANONICAL_LLM_ENABLED=${ONTOLOGY_CANONICAL_LLM_ENABLED:-0},ONTOLOGY_CANONICAL_DETERMINISTIC_THRESHOLD=${ONTOLOGY_CANONICAL_DETERMINISTIC_THRESHOLD:-0.97},ONTOLOGY_CANONICAL_LLM_MIN_CONFIDENCE=${ONTOLOGY_CANONICAL_LLM_MIN_CONFIDENCE:-0.86},ONTOLOGY_SIGNED_PROPAGATION_ENABLED=${ONTOLOGY_SIGNED_PROPAGATION_ENABLED:-1},ONTOLOGY_CRITICALITY_REVIEW_ENABLED=${ONTOLOGY_CRITICALITY_REVIEW_ENABLED:-1},ONTOLOGY_CRITICALITY_LLM_ENABLED=${ONTOLOGY_CRITICALITY_LLM_ENABLED:-1},ONTOLOGY_CRITICALITY_LOW_CONF_MAX=${ONTOLOGY_CRITICALITY_LOW_CONF_MAX:-0.72},ONTOLOGY_CRITICALITY_MIN_IMPACT_SCORE=${ONTOLOGY_CRITICALITY_MIN_IMPACT_SCORE:-0.35},ONTOLOGY_CRITICALITY_LLM_MIN_CONFIDENCE=${ONTOLOGY_CRITICALITY_LLM_MIN_CONFIDENCE:-0.65}"
  if [ -n "${CLOUD_FILES_BUCKET:-}" ]; then
    WORKER_ENV="${WORKER_ENV},CLOUD_FILES_BUCKET=${CLOUD_FILES_BUCKET}"
  fi
  if [ -n "${CLOUD_FILES_PREFIX:-}" ]; then
    WORKER_ENV="${WORKER_ENV},CLOUD_FILES_PREFIX=${CLOUD_FILES_PREFIX}"
  fi
  gcloud run deploy "$WORKER_SERVICE" \
    --image="$IMAGE" \
    --region="$REGION" \
    --project="$PROJECT_ID" \
    --platform=managed \
    --no-allow-unauthenticated \
    $SA_OPT \
    --command="/app/bin/run_ai_worker" \
    --add-cloudsql-instances="${PROJECT_ID}:${REGION}:${DB_INSTANCE}" \
    --set-env-vars="$WORKER_ENV" \
    --set-secrets="$SECRETS"
fi

APP_URL="$(gcloud run services describe "$APP_SERVICE" --region "$REGION" --project "$PROJECT_ID" --format='value(status.url)')"
echo "App URL: $APP_URL"

echo "Health checks:"
curl -fsS "${APP_URL}/health/live" && echo
curl -fsS "${APP_URL}/health/ready" && echo
if [ "$DEPLOY_WORKER" = "1" ]; then
  curl -fsS "${APP_URL}/ai/worker/health" && echo
fi

echo "Deploy complete."
echo "Rollback command example:"
echo "ROLLBACK_TAG=<previous_tag> PROJECT_ID=$PROJECT_ID REGION=$REGION REPO=$REPO APP_SERVICE=$APP_SERVICE WORKER_SERVICE=$WORKER_SERVICE DB_INSTANCE=$DB_INSTANCE ./bin/rollback_cloud_run.sh"
